# ─── Helper functions ───────────────────────────────────────────────

weaviate_count() {
    local port="$1" class="$2"
    curl -s "http://localhost:${port}/v1/graphql" \
        -H 'Content-Type: application/json' \
        -d "{\"query\":\"{ Aggregate { ${class} { meta { count } } } }\"}" 2>/dev/null \
    | python3 -c "
import sys,json
try:
    d=json.load(sys.stdin)
    print(d['data']['Aggregate']['${class}'][0]['meta']['count'])
except: print('—')
" 2>/dev/null || echo "—"
}

mongo_count() {
    local port="$1" db="$2" collection="$3"
    docker exec mongodb mongosh --quiet -u admin -p password123 --authenticationDatabase admin --eval "db.getSiblingDB('${db}').${collection}.countDocuments()" 2>/dev/null || echo "—"
}

file_count() {
    find "$1" -name "*.${2}" 2>/dev/null | grep -v node_modules | grep -v .git | grep -v vendor | grep -v __pycache__ | wc -l | tr -d ' '
}

