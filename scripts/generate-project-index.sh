## Core Concepts

### CHISG (Contextualised Hierarchical Iterative Semantic Groupings)
A method of parsing and validating information for vector database ingestion that:
- Maps semantic relationships between skills and concepts
- Enables gap analysis in learning pathways
- Reduces AI hallucinations through grounded knowledge
- Uses 8 extraction rules and 13 controlled relations

**Key files**: \`docs/chisg/CHISG_KNOWLEDGE_GRAPH_ARCHITECTURE.md\`, \`data/chisg/extraction_full_sonnet.json\`

### ETP (Emergent Tendency Profiles)
9 biological spectrums that describe learner tendencies:

| Spectrum | Range |
|----------|-------|
| social_gravity | Introvert ↔ Extrovert |
| energy_directionality | Task focus ↔ Social focus |
| voltage_sensitivity | Calm baseline ↔ High reactivity |
| threat_response | Approach ↔ Avoid |
| care_response | Independent ↔ Nurturing |
| risk_tolerance | Risk-averse ↔ Risk-seeking |
| integrity_logic | Flexible ↔ Rigid principles |
| mirror_neuron_tuning | Low empathy ↔ High empathy |
| orderliness | Spontaneous ↔ Structured |

Plus 2 global moderators: \`pilot_strength\`, \`current_load\`

**Key files**: \`esp-organizer/internal/domain/etp/spectra.go\`

### Scoped Semantic Thesaurus
Maps terminology differences across domains so that semantically equivalent but lexically different terms can be recognized:
- ${MONGO_THESAURUS_GROUPS} groups, ${MONGO_THESAURUS_ENTRIES} entries in MongoDB
- Bridges subjects (e.g., "dissipation" in physics = "inefficiency" in general use)

