else
    LAO_COURSES="?" LAO_MODULES="?" LAO_TOPICS="?" LAO_LESSONS="?" LAO_KEYWORDS="?"
fi

# CHISG extraction
EXTRACTION_FILE="${CODING}/assist/data/chisg/extraction_full_sonnet.json"
if [ -f "$EXTRACTION_FILE" ]; then
    EXTRACTION_COUNT=$(python3 -c "
import json
with open('${EXTRACTION_FILE}') as f:
    d = json.load(f)
total_links = sum(len(e.get('links',[])) for e in d.get('extractions',[]))
print(f\"{len(d.get('extractions',[]))} defs, {total_links} links\")
" 2>/dev/null || echo "?")
else
    EXTRACTION_COUNT="not found"
fi

# Docker containers
CONTAINERS=$(docker ps --format '{{.Names}}|{{.Image}}|{{.Status}}' 2>/dev/null | sort)

# File counts
